import "server-only";
import ExcelJS from "exceljs";
import { TABLE_COLUMNS } from "@/server/ai/tools";

type Row = Record<string, string | number | null>;

/**
 * Spreadsheet formula injection guard: text coming from the source system (names,
 * designations…) that starts with = + - @ or a control character would be evaluated
 * by Excel/LibreOffice as a formula. Prefix it with an apostrophe so it stays text.
 */
export function safeCell(v: string | number | null | undefined): string | number {
  if (v === null || v === undefined) return "";
  if (typeof v === "number") return v;
  return /^[=+\-@\t\r]/.test(v) ? `'${v}` : v;
}

/**
 * Builds the candidate export. Only the approved projection (TABLE_COLUMNS) is written —
 * the same columns the user already sees on screen. Returns xlsx bytes.
 */
export async function buildCandidatesWorkbook(opts: {
  title: string;
  filters: string;
  rows: Row[];
  groups?: { label: string; count: number }[] | null;
  generatedBy: string;
}): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "Data Intelligence";
  wb.created = new Date();

  const navy = "FF123F6B";
  const header = (ws: ExcelJS.Worksheet, labels: string[]) => {
    const row = ws.addRow(labels);
    row.font = { bold: true, color: { argb: "FFFFFFFF" } };
    row.eachCell((c) => {
      c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: navy } };
      c.alignment = { vertical: "middle" };
    });
    ws.views = [{ state: "frozen", ySplit: row.number }];
  };

  const summary = wb.addWorksheet("Summary");
  summary.columns = [{ width: 24 }, { width: 70 }];
  summary.addRow(["Report", opts.title]).font = { bold: true };
  summary.addRow(["Filters", safeCell(opts.filters)]);
  summary.addRow(["Records", opts.rows.length]);
  summary.addRow(["Generated", new Date().toLocaleString("en-IN")]);
  summary.addRow(["Generated by", safeCell(opts.generatedBy)]);
  summary.addRow(["Note", "Approved fields only. Contact, identity, bank and salary data are not included."]);

  if (opts.groups?.length) {
    const g = wb.addWorksheet("Breakdown");
    g.columns = [{ width: 50 }, { width: 14 }];
    header(g, ["Group", "Candidates"]);
    for (const r of opts.groups) g.addRow([safeCell(r.label), r.count]);
    g.addRow(["Total", opts.groups.reduce((s, r) => s + r.count, 0)]).font = { bold: true };
  }

  const ws = wb.addWorksheet("Candidates");
  ws.columns = TABLE_COLUMNS.map((c) => ({ key: c.key, width: c.key === "name" || c.key === "project" || c.key === "designation" || c.key === "subProject" ? 36 : 14 }));
  header(ws, TABLE_COLUMNS.map((c) => c.label));
  for (const r of opts.rows) ws.addRow(TABLE_COLUMNS.map((c) => safeCell(r[c.key])));
  ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: TABLE_COLUMNS.length } };

  return Buffer.from(await wb.xlsx.writeBuffer());
}
